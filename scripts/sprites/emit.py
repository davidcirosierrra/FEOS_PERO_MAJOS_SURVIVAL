# Builds src/voxel/sprites.gen.ts from the painter scripts (python3 scripts/sprites/emit.py).
# Needs Pillow for the PNG previews.
import importlib.util, os
HERE = os.path.dirname(os.path.abspath(__file__))
os.chdir(HERE)  # previews (PNG) land next to the scripts
import sys; sys.path.insert(0, HERE)
def load(name):
    spec = importlib.util.spec_from_file_location(name, os.path.join(HERE, f'{name}.py'))
    m = importlib.util.module_from_spec(spec); spec.loader.exec_module(m); return m
b = load('bassist'); p = load('pig'); f = load('fans'); it = load('items'); fe = load('felipe'); rf = load('rifle'); sc = load('scenery'); uf = load('umbrella_fp'); bd = load('band')
def ts(o, name):
    pal = ', '.join(f"{k}: '{v}'" for k, v in o.pal.items() if any(k in r for r in o.rows()))
    rows = ''.join(f"\n    '{r}'," for r in o.rows())
    return f"export const {name}: Pattern = {{\n  palette: {{ {pal} }},\n  rows: [{rows}\n  ],\n}}\n"
out = ["// Generated from the pixel-art painter scripts (scripts/sprites). Outlined, '.' = empty.\n", "import type { Pattern } from './patterns'\n\n"]
out.append(ts(b.o, 'BASSIST')); out.append(ts(p.o, 'PIG'))
for k, S in bd.BAND.items(): out.append(ts(S, 'BAND_' + k))
names = {'metal':'FAN_METAL','bandtee':'FAN_BANDTEE','tourist':'FAN_TOURIST','punk':'FAN_PUNK'}
for k, S in f.out.items(): out.append(ts(S.outline(), names[k]))
for k, S in it.out.items(): out.append(ts(S.outline(), k.upper()))
out.append(ts(uf.o, 'UMBRELLA_FP')); out.append(ts(sc.W, 'WALL_TILE')); out.append(ts(sc.Rf, 'ROOF_TILE')); out.append(ts(sc.St, 'STAGE'))
for k, S in rf.parts.items(): out.append(ts(S, 'RIFLE_' + k.upper()))
for k, S in fe.parts.items(): out.append(ts(S, 'FELIPE_' + k.upper()))
open(os.path.join(HERE, '..', '..', 'src', 'voxel', 'sprites.gen.ts'),'w').write('\n'.join(out))

# Bosses (parts + layout), what they throw, and the victory stage -> src/voxel/bosses.gen.ts
bo = load('bosses'); sw = load('stage_win')
def lit(o):
    pal = ', '.join(f"{k}: '{v}'" for k, v in o.pal.items() if any(k in r for r in o.rows()))
    rows = ', '.join(f"'{r}'" for r in o.rows())
    return f"{{ palette: {{ {pal} }}, rows: [{rows}] }}"
g = ["// Generated by scripts/sprites/emit.py from bosses.py and stage_win.py. Do not edit by hand.\n", "import type { Pattern } from './patterns'\n",
     "export type BossPart = { name: string; pattern: Pattern; col: number; row: number; front?: boolean }",
     "/** Parts are listed in the order they break off; the last one is the core. */",
     "export type BossArt = { grid: { w: number; h: number }; parts: BossPart[] }\n",
     "export const BOSS_ART: Record<string, BossArt> = {"]
for k, B in bo.BOSSES.items():
    g.append(f"  {k}: {{\n    grid: {{ w: {B.w + 2}, h: {B.h + 2} }},\n    parts: [")
    for name, S, x, y, front in B.parts:
        g.append(f"      {{ name: '{name}', col: {x}, row: {y},{' front: true,' if front else ''} pattern: {lit(S)} }},")
    g.append("    ],\n  },")
g.append("}\n\nexport const BOSS_SHOTS: Record<string, Pattern> = {")
for k, S in bo.SHOTS.items(): g.append(f"  {k}: {lit(S.outline())},")
g.append("}\n")
g.append(f"/** Light cans on the truss of WIN_STAGE: [x, colour key]. */\nexport const WIN_CANS: [number, string][] = {[list(c) for c in sw.CANS]}\n".replace("'x'", "'pink'").replace("'y'", "'yellow'").replace("'c'", "'cyan'").replace("'r'", "'red'"))
g.append(f"export const WIN_STAGE: Pattern = {lit(sw.S)}\n")
open(os.path.join(HERE, '..', '..', 'src', 'voxel', 'bosses.gen.ts'),'w').write('\n'.join(g))
print('ok')
